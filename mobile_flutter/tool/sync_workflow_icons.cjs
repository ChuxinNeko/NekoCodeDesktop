// Run from any directory: node mobile_flutter/tool/sync_workflow_icons.cjs
// Reuses desktop SVGs and file-name rules; no hand-drawn substitutes.
const fs = require('node:fs');
const path = require('node:path');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const families = [require('react-icons/si'), require('react-icons/di'), require('react-icons/tb')];
const tabler = require('@tabler/icons-react');
const root = path.resolve(__dirname, '../..');
const mobile = path.join(root, 'mobile_flutter');
const output = path.join(mobile, 'assets/workflow');
fs.mkdirSync(output, { recursive: true });
const source = fs.readFileSync(path.join(root, 'src/renderer/src/lib/fileIcons.tsx'), 'utf8');
const rendered = new Set();
function asset(icon, color) {
  const name = `${icon}-${color.slice(1).toLowerCase()}`;
  if (!rendered.has(name)) {
    const component = families.map(f => f[icon]).find(Boolean);
    if (!component) throw new Error(`Missing desktop icon ${icon}`);
    const svg = renderToStaticMarkup(React.createElement(component))
      .replaceAll('currentColor', color);
    fs.writeFileSync(path.join(output, `${name}.svg`), svg);
    rendered.add(name);
  }
  return name;
}
function mapping(name) {
  const block = source.match(new RegExp(`const ${name}[^=]*= ([\\s\\S]*?)\\n[}\\]];`))[1];
  const entries = [];
  const pattern = /(?:"([^"\n]+)"|([\w]+))\s*:\s*spec\((\w+),\s*"(#[\da-fA-F]+)"\)|\["([^"\n]+)",\s*spec\((\w+),\s*"(#[\da-fA-F]+)"\)\]/g;
  for (const match of block.matchAll(pattern)) {
    entries.push([match[1] || match[2] || match[5], asset(match[3] || match[6], match[4] || match[7])]);
  }
  if (!entries.length) throw new Error(`No mappings for ${name}`);
  return Object.fromEntries(entries);
}
const names = mapping('NAME_ICONS');
const prefixes = mapping('NAME_PREFIX_ICONS');
const extensions = mapping('EXT_ICONS');
for (const [name, icon] of Object.entries({
  file: 'IconFile', search: 'IconSearch', folder: 'IconFolder',
  server: 'IconServer', globe: 'IconGlobe', edit: 'IconPencil',
  tool: 'IconTool', warning: 'IconAlertTriangle', spinner: 'IconLoader2',
})) {
  fs.writeFileSync(path.join(output, `${name}.svg`),
    renderToStaticMarkup(React.createElement(tabler[icon])).replaceAll('currentColor', '#ffffff'));
}
fs.writeFileSync(path.join(output, 'console.svg'),
  fs.readFileSync(path.join(root, 'src/renderer/public/central-icons-reversed/console.svg'), 'utf8')
    .replaceAll('currentColor', '#ffffff'));
const map = (name, entries) => `const ${name} = <String, String>{\n`
  + Object.entries(entries).map(([key, value]) => `  '${key}': '${value}',`).join('\n')
  + '\n};\n';
fs.writeFileSync(path.join(mobile, 'lib/features/chat/desktop_workflow_icons.dart'),
  '// Generated by tool/sync_workflow_icons.cjs from desktop fileIcons.tsx.\n'
  + map('desktopFileNames', names) + '\n' + map('desktopFilePrefixes', prefixes)
  + '\n' + map('desktopFileExtensions', extensions));
console.log(`Synced ${rendered.size + 10} desktop SVG icons.`);
